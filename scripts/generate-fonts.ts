/**
 * Writes lib/font-catalog.json and components/editor/font-faces.ts from the curated list below and
 * each @fontsource package's metadata. Run with `pnpm fonts:generate` after changing the list (and
 * adding or removing the matching @fontsource package).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { FONT_FAMILIES } from "../constants/fonts";

type Category = keyof typeof FONT_FAMILIES;

type Metadata = { family: string; weights: number[]; styles: string[]; subsets: string[] };

const root = join(import.meta.dirname, "..");
const catalog: { family: string; category: Category; bold: boolean; italic: boolean }[] = [];
const imports: string[] = [];

for (const [category, ids] of Object.entries(FONT_FAMILIES) as [Category, readonly string[]][]) {
  for (const id of ids) {
    const meta = JSON.parse(readFileSync(join(root, "node_modules/@fontsource", id, "metadata.json"), "utf8")) as Metadata;
    if (!meta.subsets.includes("latin-ext")) throw new Error(`${id} does not include latin-ext`);
    const bold = meta.weights.includes(700);
    const italic = meta.styles.includes("italic");
    catalog.push({ family: meta.family, category, bold, italic });
    for (const weight of bold ? [400, 700] : [400]) {
      imports.push(`import "@fontsource/${id}/${weight}.css";`);
      if (italic) imports.push(`import "@fontsource/${id}/${weight}-italic.css";`);
    }
  }
}

writeFileSync(join(root, "lib/font-catalog.json"), `${JSON.stringify(catalog, null, 2)}\n`);
writeFileSync(
  join(root, "components/editor/font-faces.ts"),
  [
    "// Generated by scripts/generate-fonts.ts; do not edit by hand.",
    "// Each file only declares @font-face rules: the browser downloads a face (and only the unicode",
    "// subsets the text needs) when text first uses it.",
    ...imports,
    "",
  ].join("\n"),
);
console.log(`${catalog.length} families, ${imports.length} face stylesheets`);
